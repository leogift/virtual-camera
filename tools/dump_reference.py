#!/usr/bin/env python3
"""
转储 Python 版的几何参考数据, 供 C++ 对拍使用。

输出格式 (纯文本, 每行一条记录, 便于 C++ 用 sscanf 读、也便于人眼查):
    CAMERA <kind> <w> <h> <k1> <k2> <k3> <k4> <cx> <cy>
    PROJ <kind> <X> <Y> <Z> <u> <v>
    UNPROJ <kind> <u> <v> <rx> <ry> <rz> <theta_deg> <conv>
    MAP <kind> <src_kind> <yaw> <pitch> <roll> <W> <H> <mx0,my0;mx1,my1;...>

只写"能独立构造"的量, 不写内部中间变量 —— 对拍要能区分"公式错"和"实现差"。

用法::

    python tools/dump_reference.py --out cpp/tests/data/ref.txt
"""

from __future__ import annotations

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from vcam import FisheyeCamera, GridConverter, VirtualCamera   # noqa: E402
from vcam.models import (EnhancedFThetaModel, KannalaBrandtModel,  # noqa: E402
                         PinholeModel, RadialPolyModel)

FS_K = [339.749, -31.988, 48.275, -7.201]


def build_models():
    """返回 {name: model}。name 与 C++ 侧 vc_cam_make_* 的调用一一对应。"""
    return {
        "radial": RadialPolyModel(1280, 966, FS_K, cx=643.942, cy=479.907),
        "kb": KannalaBrandtModel(640, 480, fx=300.0, fy=300.0, cx=319.5, cy=239.5,
                                 k1=0.02, k2=-0.004, k3=0.001, k4=-0.0001),
        "pinhole": PinholeModel(640, 480, fx=500.0, fy=500.0, cx=320.0, cy=240.0),
        "eftheta": EnhancedFThetaModel(1920, 1536, [340.0, -2.0, 1.0, -0.2],
                                       c=1.0, d=0.02, e=-0.01, cx=960, cy=768),
    }


def write_camera(f, name, m):
    """各模型取系数的字段不同: KB 用 k1..k4, 多项式类用 .k 列表。"""
    if m.model_name == "kb":
        ks = [m.k1, m.k2, m.k3, m.k4]
    elif hasattr(m, "k"):
        ks = list(m.k) + [0.0] * (4 - len(m.k))
    else:
        ks = [0.0, 0.0, 0.0, 0.0]
    if m.model_name == "pinhole":
        # pinhole 的 k1..k4 是畸变系数, 这里只测无畸变分支
        ks = [0.0, 0.0, 0.0, 0.0]
    f.write(f"CAMERA {name} {m.width} {m.height} "
            f"{ks[0]:.17g} {ks[1]:.17g} {ks[2]:.17g} {ks[3]:.17g} "
            f"{m.cx:.17g} {m.cy:.17g}\n")


def write_proj(f, name, m, rng):
    # 相机系单位方向: 覆盖到 100 度入射角, 含图像外与后半球
    n = 300
    th = rng.uniform(0, np.radians(100), n)
    ph = rng.uniform(0, 2 * np.pi, n)
    P = np.stack([np.sin(th) * np.cos(ph), np.sin(th) * np.sin(ph), np.cos(th)], -1)
    u, v = m.project(P[:, 0], P[:, 1], P[:, 2])
    for i in range(n):
        f.write(f"PROJ {name} {P[i,0]:.17g} {P[i,1]:.17g} {P[i,2]:.17g} "
                f"{u[i]:.17g} {v[i]:.17g}\n")


def write_unproj(f, name, m, rng):
    # 图像内均匀取点, 外加边界点
    us = list(rng.uniform(0, m.width - 1, 200)) + [0.0, m.width - 1,
                                                   (m.width - 1) / 2]
    vs = list(rng.uniform(0, m.height - 1, 200)) + [0.0, m.height - 1,
                                                    (m.height - 1) / 2]
    res = m.unproject(np.array(us), np.array(vs))
    for i in range(len(us)):
        r = res.ray[i]
        f.write(f"UNPROJ {name} {us[i]:.17g} {vs[i]:.17g} "
                f"{r[0]:.17g} {r[1]:.17g} {r[2]:.17g} "
                f"{res.theta_deg[i]:.17g} {1 if res.converged[i] else 0}\n")


def write_map(f, tag, src_model, dst_model, yaw, pitch, roll, w, h):
    """
    写一条 MAP 记录。

    w/h 必须**等于目标相机的实际尺寸**: 记录里的尺寸决定对拍端分配多大的
    缓冲区, 而构建端按 dst.width 写。两者不一致就是越界写 —— 曾经 identity
    那条写成 320x240 而模型是 1280x966, 对拍端直接 SIGSEGV。
    """
    assert dst_model.width == w and dst_model.height == h, (
        f"MAP {tag}: 记录尺寸 {w}x{h} 与目标模型 "
        f"{dst_model.width}x{dst_model.height} 不符")
    src = FisheyeCamera(name="src", model=src_model)
    dst = FisheyeCamera(name="vp", model=dst_model)
    conv = GridConverter(src, dst, yaw_delta_deg=yaw, pitch_delta_deg=pitch,
                         roll_delta_deg=roll)
    mx, my, st = conv.build_maps()
    # 抽稀: 全图太大, 取等间隔 1000 个点足以覆盖整片区域。
    # **索引直接写进记录**, 不让 C++ 这边自己算 linspace —— numpy 的
    # .astype(int) 是截断(76), 而 C++ 的 round 给 77, 一点错位在梯度大的
    # 地方就放大成 1279 px 的"对拍失败", 查起来极费劲。
    idx = np.linspace(0, mx.size - 1, 1000).astype(int)
    pairs = ";".join(f"{int(i)},{float(mx.flat[i]):.9g},{float(my.flat[i]):.9g}"
                     for i in idx)
    f.write(f"MAP {tag} {yaw!r} {pitch!r} {roll!r} {w} {h} {st.valid} "
            f"{st.out_of_source} {pairs}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="cpp/tests/data/ref.txt")
    ap.add_argument("--seed", type=int, default=20240)
    args = ap.parse_args()

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    models = build_models()
    rng = np.random.default_rng(args.seed)

    with open(args.out, "w", encoding="utf-8") as f:
        f.write(f"# vcam parity reference, seed={args.seed}\n")
        f.write(f"# generated by tools/dump_reference.py; do not edit\n")
        for name, m in models.items():
            write_camera(f, name, m)
        for name, m in models.items():
            write_proj(f, name, m, rng)
        for name, m in models.items():
            write_unproj(f, name, m, rng)

        # 网格: 源 FV radial -> 虚拟 pinhole, 三组姿态
        vp = VirtualCamera.from_fov(320, 240, 150.0, 120.0, name="vp")
        for yaw in (-45.0, 0.0, 45.0):
            write_map(f, "fv_yaw", models["radial"], vp.model, yaw, 0.0, 0.0, 320, 240)
        write_map(f, "fv_pitch", models["radial"], vp.model, 0.0, 15.0, 0.0, 320, 240)
        write_map(f, "fv_roll", models["radial"], vp.model, 0.0, 0.0, 10.0, 320, 240)
        # 同模型同尺寸: 恒等映射 (必须是 1280x966, 与 radial 模型一致)
        write_map(f, "identity", models["radial"], models["radial"], 0.0, 0.0, 0.0,
                  1280, 966)

    print(f"wrote {args.out}")
    n = sum(1 for _ in open(args.out, encoding="utf-8"))
    print(f"  {n} lines")
    print(f"  models: {', '.join(models)}")


if __name__ == "__main__":
    main()
